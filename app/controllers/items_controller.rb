# The items of an inventory.
#
# Items may be added, changed and deleted by the owner of the inventory, by
# the administrators, by the users that were granted write access and - when
# the inventory is public - by everybody who is signed in.
class ItemsController < ApplicationController
  include Paginates
  include DeniesAccess

  before_action :require_authentication, only: [:new, :create, :edit, :update, :destroy]
  before_action :set_inventory, only: [:index, :new, :create]
  before_action :set_item, only: [:show, :edit, :update, :destroy]
  before_action :require_write_access, only: [:new, :create, :edit, :update, :destroy]

  # The table of items of an inventory.
  def index
    @fields = @inventory.fields.in_table
    @items = paginate(search_scope(@inventory.items.includes(:created_by, field_values: :field).ordered))

    respond_to do |format|
      format.html
      format.json do
        render json: {
          inventory: { id: @inventory.id, title: @inventory.title },
          fields: @fields.map { |field| field_json(field) },
          items: @items.map { |item| item_json(item) }
        }
      end
    end
  end

  # A single item.
  def show
    @fields = @inventory.fields

    respond_to do |format|
      format.html
      format.json { render json: item_json(@item) }
    end
  end

  # The form of a new item.
  #
  # The form already shows the custom id that the system will use, so that
  # the user can change it before the item is stored.
  def new
    @item = @inventory.items.new(custom_id: preview_custom_id)
    build_field_values(@item)

    respond_to do |format|
      format.html
      format.json { render json: item_json(@item) }
    end
  end

  # Creates an item.
  #
  # The custom id is generated by the system when the form does not contain
  # one; the database rejects an id that is already used in the inventory.
  def create
    @item = @inventory.items.new(custom_id: submitted_custom_id.presence || generated_custom_id)
    @item.created_by = current_user
    assign_values(@item, submitted_values)

    if @item.save
      respond_to do |format|
        format.html { redirect_to @inventory, notice: t("items.created") }
        format.json { render json: item_json(@item), status: :created }
      end
    else
      build_field_values(@item)
      respond_to do |format|
        format.html { render :new, status: :unprocessable_entity }
        format.json { render json: { error: "invalid", errors: @item.errors.full_messages }, status: :unprocessable_entity }
      end
    end
  rescue ActiveRecord::RecordNotUnique
    # Somebody else used the same custom id in the meantime.
    @item.errors.add(:custom_id, t("items.custom_id_taken"))
    build_field_values(@item)

    respond_to do |format|
      format.html { render :new, status: :unprocessable_entity }
      format.json { render json: { error: "invalid", errors: @item.errors.full_messages }, status: :unprocessable_entity }
    end
  rescue CustomId::DuplicateError => e
    @item.errors.add(:custom_id, e.message)
    build_field_values(@item)

    respond_to do |format|
      format.html { render :new, status: :unprocessable_entity }
      format.json { render json: { error: "invalid", errors: @item.errors.full_messages }, status: :unprocessable_entity }
    end
  end

  # The form of an item.
  def edit
    @fields = @inventory.fields

    respond_to do |format|
      format.html
      format.json { render json: item_json(@item) }
    end
  end

  # Updates an item.
  #
  # The item uses optimistic locking: when the version the browser sent is
  # not the current one, the save is rejected with a conflict.  The custom id
  # and the version are only changed when the browser really sent them.
  def update
    attributes = {}
    attributes[:custom_id] = submitted_custom_id if params[:item]&.key?(:custom_id)
    attributes[:lock_version] = submitted_lock_version if params[:item]&.key?(:lock_version)

    @item.assign_attributes(attributes)
    assign_values(@item, submitted_values)

    if @item.valid? && @item.save
      respond_to do |format|
        format.html { redirect_to @inventory, notice: t("items.updated") }
        format.json { render json: item_json(@item) }
      end
    else
      respond_to do |format|
        format.html { render :edit, status: :unprocessable_entity }
        format.json do
          render json: { error: "invalid", errors: @item.errors.full_messages, version: @item.lock_version },
                 status: :unprocessable_entity
        end
      end
    end
  rescue ActiveRecord::StaleObjectError
    respond_to do |format|
      format.html { redirect_to edit_item_path(@item), alert: t("items.conflict") }
      format.json { render json: conflict_json, status: :conflict }
    end
  end

  # Deletes an item.
  def destroy
    @item.destroy!

    respond_to do |format|
      format.html { redirect_to @inventory, notice: t("items.destroyed") }
      format.json { head :no_content }
    end
  end

  private

  def set_inventory
    @inventory = Inventory.find(params[:inventory_id])
  end

  def set_item
    @item = Item.includes(:inventory, field_values: :field).find(params[:id])
    @inventory = @item.inventory
  end

  # Only the users that may write items of this inventory get further.
  def require_write_access
    return if @inventory.writable_by?(current_user)

    respond_to do |format|
      format.html do
        flash.now[:alert] = t("items.not_allowed")
        render "items/index", status: :forbidden
      end
      format.json { render json: { error: "forbidden" }, status: :forbidden }
    end
  end

  # The search of the items table.
  def search_scope(scope)
    query = params[:q].to_s.strip
    return scope if query.blank?

    Search.new(query, inventory: @inventory).items.includes(:created_by, field_values: :field)
  end

  # The custom id the form sent, or nil when the system has to generate one.
  def submitted_custom_id
    value = params.dig(:item, :custom_id)
    value.present? ? value.to_s.strip : nil
  end

  # The version of the item the form sent.
  #
  # The value is written back into the record before it is saved, so that
  # Active Record can tell whether the item was changed by somebody else in
  # the meantime.
  def submitted_lock_version
    value = params.dig(:item, :lock_version)
    value.present? ? value.to_i : nil
  end

  # Builds a custom id from the format of the inventory.
  def generated_custom_id
    CustomId::Generator.new(@inventory).generate
  end

  # The custom id that is shown in the form of a new item.
  def preview_custom_id
    generated_custom_id
  rescue CustomId::DuplicateError
    nil
  end

  # The values of the custom fields the form sent.
  def submitted_values
    values = params.dig(:item, :values)
    values.respond_to?(:to_unsafe_h) ? values.to_unsafe_h : (values || {})
  end

  # Writes the values of the form into the field values of the item.
  #
  # Every value is converted into the type of its field: "1" and "true"
  # become true, an empty number becomes nil, and so on.  A check box that
  # was not sent at all means "not checked"; every other field that is not
  # in the form keeps the value it had.
  def assign_values(item, values)
    @inventory.fields.each do |field|
      boolean = field.field_type == Field::BOOLEAN
      next unless boolean || values.key?(field.id.to_s)

      field_value = item.field_values.detect { |value| value.field_id == field.id } ||
                    item.field_values.build(field_id: field.id)
      field_value.value = boolean ? boolean_value(values[field.id.to_s]) : values[field.id.to_s]
    end
  end

  # Builds an empty field value for every field of the inventory, so that
  # the form always shows the same inputs.
  def build_field_values(item)
    @inventory.fields.each do |field|
      next if item.field_values.any? { |field_value| field_value.field_id == field.id }

      field_value = item.field_values.build(field_id: field.id)
      field_value.value = field.field_type == Field::BOOLEAN ? false : nil
    end
  end

  # Turns the value of a check box into true or false.
  def boolean_value(raw)
    ActiveModel::Type::Boolean.new.cast(raw) || false
  end

  def conflict_json
    {
      error: "conflict",
      message: t("items.conflict"),
      version: @item.reload.lock_version
    }
  end

  def item_json(item)
    {
      id: item.id,
      custom_id: item.custom_id,
      inventory_id: item.inventory_id,
      values: item.values,
      likes_count: item.likes_count,
      liked_by_me: item.liked_by?(current_user),
      created_by: item.created_by&.display_name,
      created_at: item.created_at,
      updated_at: item.updated_at,
      version: item.lock_version,
      can_edit: item.editable_by?(current_user),
      url: item_path(item)
    }
  end

  def field_json(field)
    {
      id: field.id,
      title: field.title,
      description: field.description,
      field_type: field.field_type,
      show_in_table: field.show_in_table,
      position: field.position
    }
  end
end
